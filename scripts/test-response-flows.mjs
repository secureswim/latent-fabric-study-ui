import assert from 'node:assert/strict';
import {DEFAULT_STATE,responseTarget,latentSnapshot} from '../app/study.ts';
const s={...DEFAULT_STATE,designIndex:10002000,previousDesignIndex:8,anchors:[8,10001000],visitedDesigns:[8,10001000,10002000],branchHeads:{b0:10002000,b1:10003000}};
assert.equal(responseTarget(s,'navigate').designIndex,s.designIndex);
assert.equal(responseTarget(s,'anchor').anchors.at(-1),s.designIndex);
assert.equal(responseTarget(s,'return-anchor').designIndex,10001000);
const branch=responseTarget(s,'branch');assert.equal(branch.designIndex,10001000);assert.equal(branch.branch,'b2');assert.equal(branch.branchHeads.b0,s.designIndex);
assert.equal(responseTarget(s,'timeline-branch').designIndex,10003000);
assert.deepEqual(responseTarget(s,'undo').visitedDesigns,[8,10001000]);
assert.equal(responseTarget(s,'undo').designIndex,10001000);
const lock=responseTarget(s,'lock');assert.equal(lock.lockedDesignIndex,s.designIndex);
assert.equal(responseTarget({...s,...lock},'unlock').locked.length,0);
const reset=responseTarget(s,'reset');assert.deepEqual(reset.anchors,[]);assert.deepEqual(reset.branchHeads,{b0:8});
assert.equal(responseTarget(s,'local').viewScale,1.5);
assert.equal(responseTarget({...s,viewScale:1.5},'zoom-out').viewScale,.9750000000000001);
assert.equal(latentSnapshot({...s,viewScale:2}).viewScale,2);
assert.equal(responseTarget(s,'compare').designIndex,s.designIndex);
assert.equal(responseTarget(s,'history').designIndex,s.designIndex);
assert.equal(responseTarget(s,'select').designIndex,s.designIndex);
console.log('PASS: all 15 response semantics; anchors, branches, undo, locks, reset and persistent view');
